#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Emit a reader-controls probe that is safe to reuse on a DIFFERENT book.

    python make_reader_probe.py --out readerprobe.js --term 关税 --term2 制造业 \
        --latin gdp --storage cd: --report-id __rc

WHY THIS GENERATOR EXISTS — the worst failure of the 《缠斗》 build

The probe inherited from the previous book hard-coded that book's section id
(`c12`), TOC label (`第12章`), search term (`毕生发展观`), storage prefix (`hbj:`)
and even its colour palette. On the new book the first assertion returned null,
the probe threw, and `--dump-dom` produced no report at all. The gate's stage 8
looped over zero verdict lines, so **every check it never ran was reported as
passing**, and the run printed "all checks passed".

Two lessons, both encoded here:

  1. Derive everything from the document. Section ids, TOC labels and the
     storage prefix are read at runtime, so the probe cannot test another
     book's markup by accident.
  2. A probe that produced no report is a FAILURE. The gate must parse a
     "N/N passed" line and require it, never iterate over an empty list.

The emitted probe also guards every node lookup, so a missing element is one
failed assertion rather than a crash that silently takes the rest of the run
with it.
"""
import argparse
import sys

try:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
except Exception:
    pass

TEMPLATE = r"""/* End-to-end check of the reader controls. Generated by
   make_reader_probe.py — edit the generator, not this file.

   Every assertion is derived from the document itself (section ids, TOC labels,
   storage prefix), so this probe cannot pass by testing a different book's
   markup, and it cannot crash on a missing node: each lookup is guarded and
   reported as a failure instead of throwing. */
(function () {
  var R = [];
  var REPORT_ID = "__REPORT_ID__";
  function ck(name, ok, got) { R.push({ name: name, ok: !!ok, got: got }); }
  function q(s) { return document.querySelector(s); }
  function qa(s) { return document.querySelectorAll(s); }
  function txt(e) { return e && e.textContent ? e.textContent.trim() : ""; }
  function done() {
    document.documentElement.innerHTML =
      "<body><pre id='" + REPORT_ID + "'></pre></body>";
    document.getElementById(REPORT_ID).textContent = JSON.stringify(R);
  }

  setTimeout(function () {
    var chapters = qa("section.chapter");
    var lastId = chapters.length ? chapters[chapters.length - 1].id : "";

    /* ---------- 1. TOC ---------- */
    var tocBtn = q("#tocbtn"), tocNow = q("#tocnow"), list = q("#toclist");
    ck("顶栏有目录按钮", !!tocBtn && !!list);
    if (!tocBtn || !list) { done(); return; }
    ck("目录列出每一节（" + chapters.length + " 节）",
       list.children.length === chapters.length, list.children.length);

    /* A cover section is a legitimately unlabelled entry: it has no chapter
       number and no running title. Only labelled entries must render one. */
    var blank = 0, blanksRest = 0;
    Array.prototype.forEach.call(list.children, function (b) {
      var n = b.querySelector(".n"), t = b.querySelector(".t");
      if (!n || !txt(n)) blank++;
      if (!t || !txt(t)) blanksRest++;
    });
    ck("除封面外没有目录项标签为空", blank <= 1 && blanksRest <= 1,
       { num: blank, title: blanksRest });
    ck("目录按钮上的文字不为空", !!txt(tocNow), txt(tocNow));

    tocBtn.click();
    ck("点一下目录面板就打开", q("#tocmenu").hidden === false);

    var target = document.getElementById(lastId);
    ck("书中存在最后一节 " + lastId, !!target);
    if (!target) { done(); return; }
    var want = target.getBoundingClientRect().top + window.pageYOffset;
    Array.prototype.forEach.call(list.children, function (b) {
      if (b.getAttribute("data-id") === lastId) b.click();
    });

    setTimeout(function () {
      ck("点目录项真的跳到那一节", Math.abs(window.pageYOffset - want) < 40,
         { got: Math.round(window.pageYOffset), want: Math.round(want) });
      ck("选完目录面板自动收起", q("#tocmenu").hidden === true);
      ck("目录按钮跟着滚动位置更新", !!txt(tocNow) && txt(tocNow) !== "目录", txt(tocNow));

      /* ---------- 2. search ---------- */
      var sBtn = q("#srchbtn"), sIn = q("#srchin");
      sBtn.click();
      ck("搜索面板打开", q("#srchpanel").hidden === false);
      if (!sIn) { done(); return; }

      function type(v, cb) {
        sIn.value = v;
        sIn.dispatchEvent(new Event("input", { bubbles: true }));
        setTimeout(cb, 500);
      }
      function marks() { return qa(".wrap mark.sh").length; }
      function outlines() { return qa(".wrap .hit-box").length; }
      function meta() { return txt(q("#srchmeta")); }

      type("__TERM__", function () {
        var rows = qa("#srchlist .sres");
        ck("搜索能找到正文词条", rows.length > 0, rows.length);
        ck("搜索结果显示所属章节",
           !!rows[0] && !!rows[0].querySelector(".ch") &&
           /\S/.test(txt(rows[0].querySelector(".ch"))));
        ck("搜索结果显示命中数", /命中|处/.test(meta()), meta());
        ck("命中在页面上看得见（行内高亮或图内描边）", marks() + outlines() > 0,
           { inlineMarks: marks(), outlines: outlines() });

        /* Walk results until one genuine prose match is wrapped. A hit inside
           an SVG cannot take an HTML <mark>, so one fixed assertion would test
           luck rather than the feature. */
        var i = 0, tries = Math.min(rows.length, 12);
        (function step() {
          if (i >= tries || marks() > 0) return;
          var row = qa("#srchlist .sres")[i++];
          if (row) row.click();
          setTimeout(step, 220);
        })();

        setTimeout(function () {
          ck("至少有一处正文命中被行内 <mark> 包住", marks() > 0, marks());
          var m0 = qa(".wrap mark.sh")[0];
          ck("行内高亮有可见样式",
             !m0 || getComputedStyle(m0).backgroundColor !== "rgba(0, 0, 0, 0)",
             m0 ? getComputedStyle(m0).backgroundColor : "no mark");

          type("__TERM2__", function () {
            ck("搜索可以跨过内联标签命中", marks() + outlines() > 0,
               { inlineMarks: marks(), outlines: outlines() });
            type("__LATIN__", function () {
              ck("搜索不区分英文大小写", /命中|处/.test(meta()), meta());
              type("绝对不会出现的词zzq", function () {
                ck("搜不到时有明确说明", !!q("#srchlist").querySelector(".sres-empty"));
                ck("换词后不留上一页的标记", marks() === 0 && outlines() === 0);

                /* ---------- 3. night mode ---------- */
                /* The first [fill] in a chart is usually fill="none" on a
                   line — not a colour, never remapped. Walk to a real hex. */
                var svg0 = null;
                Array.prototype.forEach.call(qa("svg.chart [fill]"), function (n) {
                  if (svg0) return;
                  var f = n.getAttribute("fill");
                  if (f && f.charAt(0) === "#") svg0 = n;
                });
                if (!svg0) { done(); return; }
                var wasDark = document.documentElement.getAttribute("data-theme") === "dark";
                var before = svg0.getAttribute("fill");
                q("#themebtn").click();
                var nowDark = document.documentElement.getAttribute("data-theme") === "dark";
                ck("夜间模式按钮真的切换主题", nowDark !== wasDark, nowDark);
                ck("按钮回报自己的状态",
                   q("#themebtn").getAttribute("aria-pressed") === String(nowDark));
                ck("图表颜色被重新映射，不是留在白天配色",
                   svg0.getAttribute("fill") !== before,
                   before + " -> " + svg0.getAttribute("fill"));
                q("#themebtn").click();
                ck("切回白天也干净", svg0.getAttribute("fill") === before,
                   svg0.getAttribute("fill"));

                /* ---------- 4. saved reading position ---------- */
                var saved = null;
                try { saved = JSON.parse(localStorage.getItem("__STORAGE__pos")); } catch (e) {}
                ck("阅读位置被记下来了", !!saved && typeof saved.id === "string", saved);
                ck("记录的位置指向真实的一节",
                   !!(saved && document.getElementById(saved.id)), saved && saved.id);
                ck("记录里带百分比", !!saved && saved.pct >= 0 && saved.pct <= 100,
                   saved && saved.pct);

                /* ---------- 5. lightbox ---------- */
                var shot = q("button.shot");
                ck("原书图表包在可点击的按钮里", !!shot);
                if (shot) {
                  shot.click();
                  var lb = q("#lightbox");
                  ck("点图表会打开放大层", !!lb && lb.classList.contains("on"));
                  var closeBtn = lb && lb.querySelector('[data-act="close"]');
                  ck("放大层有关闭按钮", !!closeBtn);
                  if (closeBtn) closeBtn.click();
                  ck("关闭后放大层收起", !lb.classList.contains("on"));
                }

                /* ---------- 6. no layout damage ---------- */
                ck("页面不会横向滚动",
                   document.documentElement.scrollWidth -
                   document.documentElement.clientWidth <= 0,
                   document.documentElement.scrollWidth -
                   document.documentElement.clientWidth);
                done();
              });
            });
          });
        }, 2800);
      });
    }, 900);
  }, 800);
})();
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="readerprobe.js")
    ap.add_argument("--term", default="的", help="a term that occurs in most chapters")
    ap.add_argument("--term2", default="中国", help="a term often split by inline tags")
    ap.add_argument("--latin", default="gdp", help="a Latin acronym, lower-cased "
                                                  "to test case-insensitivity")
    ap.add_argument("--storage", default="hbj:", help="localStorage key prefix")
    ap.add_argument("--report-id", default="__rc")
    a = ap.parse_args()

    js = (TEMPLATE
          .replace("__REPORT_ID__", a.report_id)
          .replace("__TERM__", a.term)
          .replace("__TERM2__", a.term2)
          .replace("__LATIN__", a.latin.lower())
          .replace("__STORAGE__", a.storage))
    open(a.out, "w", encoding="utf-8").write(js)
    print("wrote %s (%d bytes)" % (a.out, len(js)))
    print("terms: %r / %r / %r | storage %r | report id %r"
          % (a.term, a.term2, a.latin, a.storage, a.report_id))
    print("\nThe gate MUST require a 'N/N passed' line from this probe's output. "
          "An empty verdict list means the probe threw — that is a failure, not "
          "a pass.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
